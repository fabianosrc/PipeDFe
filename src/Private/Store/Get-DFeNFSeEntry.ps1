<#
.SYNOPSIS
Reads national NFS-e fiscal entries from one company's SQLite index

.DESCRIPTION
Queries the dfe_nfse table and returns one object per row. Filters by
gerado_em (the instant the NFS-e was generated by the prefeitura), not
by DPS issuance date or service competence period. Both StartDate and
EndDate are inclusive and normalized to UTC before comparison. Omitting
either bound leaves that side unbounded. No matches produce no output.

This function does not decide which documents are eligible for delivery.

.PARAMETER Cnpj
14-character uppercase alphanumeric CNPJ of the company whose index is
queried. Must match the pattern [A-Z0-9]{14}.

.PARAMETER StartDate
Lower bound for gerado_em, inclusive. Any string accepted by
ConvertTo-DateTimeOffset is valid (ISO 8601 with or without offset).
Omit for an unbounded lower end.

.PARAMETER EndDate
Upper bound for gerado_em, inclusive. Same format rules as StartDate.
Must not be earlier than StartDate when both are supplied.

.OUTPUTS
[pscustomobject] with properties:
    chave_acesso   [string]        50-digit NFS-e access key
    numero         [string]        NFS-e sequential number
    file_path      [string]        Absolute path to the XML file
    source_sha256  [string]        SHA-256 hex of the XML file
    gerado_em      [string]        UTC ISO 8601 generation instant
    dps_emitida_em [string]        UTC ISO 8601 DPS issuance instant
    competencia    [string]        Service competence date (YYYY-MM-DD)
    status         [string][null]  Current lifecycle status
    valor_servico  [string]        Gross service value (G29 decimal)
    valor_liquido  [string]        Net service value (G29 decimal)
    valor_issqn    [string][null]  ISSQN amount (G29 decimal)
    prestador_cnpj [string][null]  Service provider CNPJ
    prestador_cpf  [string][null]  Service provider CPF
    tomador_cnpj   [string][null]  Service taker CNPJ
    tomador_cpf    [string][null]  Service taker CPF

.EXAMPLE
PS C:\> Get-DFeNFSeEntry -Cnpj '12345678000199' `
    -StartDate '2026-11-01T00:00:00Z' `
    -EndDate   '2026-11-30T23:59:59Z'

.NOTES
Private dependencies:
  Open-DFeIndexConnection,
  ConvertTo-DateTimeOffset
#>
function Get-DFeNFSeEntry {
    [CmdletBinding()]
    [OutputType([pscustomobject])]
    param (
        [Parameter(Mandatory)]
        [ValidatePattern('^(?-i)[A-Z0-9]{14}$')]
        [string]$Cnpj,

        [Parameter()]
        [string]$StartDate,

        [Parameter()]
        [string]$EndDate
    )

    $startUtc = $null
    $endUtc   = $null

    if (-not [string]::IsNullOrWhiteSpace($StartDate)) {
        $startUtc = ConvertTo-DateTimeOffset -Value $StartDate
    }

    if (-not [string]::IsNullOrWhiteSpace($EndDate)) {
        $endUtc = ConvertTo-DateTimeOffset -Value $EndDate
    }

    if ($null -ne $startUtc -and $null -ne $endUtc -and $startUtc -gt $endUtc) {
        $PSCmdlet.ThrowTerminatingError(
            [System.Management.Automation.ErrorRecord]::new(
                [System.ArgumentException]::new(
                    'StartDate must not be after EndDate.'
                ),
                'InvalidNFSeDateRange',
                [System.Management.Automation.ErrorCategory]::InvalidArgument,
                $StartDate
            )
        )
    }

    $connection = $null
    $command    = $null
    $reader     = $null

    try {
        $connection = Open-DFeIndexConnection -Cnpj $Cnpj
        $command = $connection.CreateCommand()

        $conditions = [System.Collections.Generic.List[string]]::new()

        if ($null -ne $startUtc) {
            $conditions.Add('gerado_em >= @startDate')
            $startParam = $command.Parameters.Add('@startDate', [System.Data.DbType]::String)
            $startParam.Value = $startUtc.ToString('o')
        }

        if ($null -ne $endUtc) {
            $conditions.Add('gerado_em <= @endDate')
            $endParam = $command.Parameters.Add('@endDate', [System.Data.DbType]::String)
            $endParam.Value = $endUtc.ToString('o')
        }

        $whereClause = if ($conditions.Count -gt 0) {
            'WHERE ' + ($conditions -join ' AND ')
        } else {
            [string]::Empty
        }

        $command.CommandText = @"
SELECT
    chave_acesso,
    numero,
    file_path,
    source_sha256,
    gerado_em,
    dps_emitida_em,
    competencia,
    status,
    valor_servico,
    valor_liquido,
    valor_issqn,
    prestador_cnpj,
    prestador_cpf,
    tomador_cnpj,
    tomador_cpf
FROM dfe_nfse
$whereClause
ORDER BY gerado_em ASC, chave_acesso ASC;
"@

        $reader = $command.ExecuteReader()
        while ($reader.Read()) {
            [pscustomobject]@{
                chave_acesso   = $reader.GetString(0)
                numero         = $reader.GetString(1)
                file_path      = $reader.GetString(2)
                source_sha256  = $reader.GetString(3)
                gerado_em      = $reader.GetString(4)
                dps_emitida_em = $reader.GetString(5)
                competencia    = $reader.GetString(6)
                status         = if ($reader.IsDBNull(7)) { $null } else { $reader.GetString(7) }
                valor_servico  = $reader.GetString(8)
                valor_liquido  = $reader.GetString(9)
                valor_issqn    = if ($reader.IsDBNull(10)) { $null } else { $reader.GetString(10) }
                prestador_cnpj = if ($reader.IsDBNull(11)) { $null } else { $reader.GetString(11) }
                prestador_cpf  = if ($reader.IsDBNull(12)) { $null } else { $reader.GetString(12) }
                tomador_cnpj   = if ($reader.IsDBNull(13)) { $null } else { $reader.GetString(13) }
                tomador_cpf    = if ($reader.IsDBNull(14)) { $null } else { $reader.GetString(14) }
            }
        }
    } catch {
        # Any SQLite or connection failure is surfaced here; the exception type varies
        # (SqliteException, InvalidOperationException, IOException), so a generic catch
        # is the only way to guarantee no silent partial results escape.
        $PSCmdlet.ThrowTerminatingError(
            [System.Management.Automation.ErrorRecord]::new(
                $_.Exception,
                'NFSeEntryReadFailed',
                [System.Management.Automation.ErrorCategory]::OperationStopped,
                $Cnpj
            )
        )
    } finally {
        if ($null -ne $reader) {
            $reader.Dispose()
        }

        if ($null -ne $command) {
            $command.Dispose()
        }

        if ($null -ne $connection) {
            $connection.Dispose()
        }
    }
}
