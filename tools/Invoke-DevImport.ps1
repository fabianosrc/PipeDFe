    [CmdletBinding()]
    [OutputType([void])]
    param (
        [Parameter(Mandatory)]
        [string]$Title
    )

    Write-Host ''
    Write-Host "  $Title" -ForegroundColor Cyan
    Write-Host ''
}

function Write-Success {
    [CmdletBinding()]
    [OutputType([void])]
    param (
        [Parameter(Mandatory)]
