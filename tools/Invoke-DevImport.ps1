#Requires -Version 5.1

<#
.SYNOPSIS
Imports the PipeDFe PowerShell module in development mode.

.DESCRIPTION
Performs a clean development import of the PipeDFe module directly
from the local source tree.

The script:
  1. Validates the module manifest.
  2. Removes any previously loaded instance of the module.
  3. Imports the module from its local manifest.
  4. Displays module metadata and exported commands.
  5. Optionally runs PSScriptAnalyzer against the source tree.

The script is designed for both interactive development and automation.

Exit codes:
  0 - Operation completed successfully.
  1 - Module import or validation failed.
  2 - Linting failed when -FailOnLint was specified.

.PARAMETER Quiet
Suppresses verbose output generated by Import-Module.

.PARAMETER SkipLint
Skips the PSScriptAnalyzer validation step.

.PARAMETER FailOnLint
Causes the script to exit with code 2 when PSScriptAnalyzer
reports one or more errors or warnings.

.PARAMETER PassThru
Returns a summary object containing module and lint information.
Useful when invoking this script from another PowerShell script.

.PARAMETER WhatIf
Shows what would happen without modifying the current session.

.EXAMPLE
PS C:\PipeDFe> .\tools\Invoke-DevImport.ps1

Imports the module and runs PSScriptAnalyzer.

.EXAMPLE
PS C:\PipeDFe> .\tools\Invoke-DevImport.ps1 -Quiet

Imports the module without displaying Import-Module verbose output.

.EXAMPLE
PS C:\PipeDFe> .\tools\Invoke-DevImport.ps1 -SkipLint

Imports the module without running PSScriptAnalyzer.

.EXAMPLE
PS C:\PipeDFe> .\tools\Invoke-DevImport.ps1 -FailOnLint

Imports the module and returns exit code 2 if linting reports
warnings or errors.

.EXAMPLE
PS C:\PipeDFe> $result = .\tools\Invoke-DevImport.ps1 -PassThru

Imports the module and captures the resulting summary object.

.NOTES
  File:     Invoke-DevImport.ps1
  Project:  PipeDFe
  Requires: PowerShell 5.1+
#>

[Diagnostics.CodeAnalysis.SuppressMessageAttribute(
    'PSAvoidUsingWriteHost',
    '',
    Justification = 'This script is an interactive development CLI.'
)]
[CmdletBinding(SupportsShouldProcess)]
param (
    [Parameter()]
    [switch]$Quiet,

    [Parameter()]
    [switch]$SkipLint,

    [Parameter()]
    [switch]$FailOnLint,

    [Parameter()]
    [switch]$PassThru
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

#region Constants
$Script:ModuleName   = 'PipeDFe'
$Script:ModuleRoot   = Split-Path -Path $PSScriptRoot      -Parent
$Script:ManifestPath = Join-Path  -Path $Script:ModuleRoot -ChildPath "$Script:ModuleName.psd1"
$Script:SourcePath   = Join-Path  -Path $Script:ModuleRoot -ChildPath 'src'

$Script:AnalyzerSettingsPath = Join-Path -Path $Script:ModuleRoot -ChildPath 'PSScriptAnalyzerSettings.psd1'
#endregion

#region Helper Functions
